// The schema is the source of truth for activity type/interface counter membership.
const fs = require('fs')
const path = require('path')
const { parse, Kind } = require('graphql')
const prettier = require('prettier')
const root = path.resolve(__dirname, '..')
const schema = parse(fs.readFileSync(path.join(root, 'schema.graphql'), 'utf8'))
const definitions = schema.definitions
const counterName = name => name.replace(/^[A-Z]+(?=[A-Z][a-z]|$)|^[A-Z]/, x => x.toLowerCase()) + 'Count'
const types = definitions.filter(d => d.kind === Kind.OBJECT_TYPE_DEFINITION && d.interfaces.some(i => i.name.value === 'Event'))
const counters = definitions.find(d => d.name?.value === 'CounterEntity').fields.filter(f => f.name.value !== 'id').map(f => f.name.value)
const expected = new Set()
const cases = types.map(type => {
  const fields = [counterName(type.name.value), ...type.interfaces.map(i => counterName(i.name.value))]
  fields.forEach(f => expected.add(f))
  return `  if (type == '${type.name.value}') return [${fields.map(f => `'${f}'`).join(', ')}]`
})
if (counters.length !== expected.size || counters.some(c => !expected.has(c))) {
  throw new Error(`CounterEntity must match all activity types/interfaces. Missing: ${[...expected].filter(c => !counters.includes(c))}; extra: ${counters.filter(c => !expected.has(c))}`)
}
const output = `// Generated by scripts/generate-event-counters.cjs from schema.graphql. Do not edit.
import { BigInt, Value } from '@graphprotocol/graph-ts'
import { CounterEntity } from '../types/schema'

export function counterFields(type: string): string[] {
${cases.join('\n')}
  throw new Error('Unknown activity type: ' + type)
}

export function loadCounters(): CounterEntity {
  let counter = CounterEntity.load('0')
  if (counter == null) {
    counter = new CounterEntity('0')
${counters.map(c => `    counter.set('${c}', Value.fromBigInt(BigInt.fromI32(0)))`).join('\n')}
  }
  return counter as CounterEntity
}
`
const interfaceNames = [...new Set(types.flatMap(t => t.interfaces.map(i => i.name.value)))]
const assertionOutput = `// Generated from schema.graphql by scripts/generate-event-counters.cjs.
import { assert, countEntities } from 'matchstick-as/assembly/index'
import { CounterEntity } from '../src/types/schema'

// Compare counters to actual persisted entity counts, including zero counts and
// every overlapping interface, after each handler scenario.
export function assertAllCounters(): void {
  let types: string[] = [${types.map(t => `'${t.name.value}'`).join(', ')}]
  let typeCounters: string[] = [${types.map(t => `'${counterName(t.name.value)}'`).join(', ')}]
  let interfaceCounters: string[] = [${interfaceNames.map(n => `'${counterName(n)}'`).join(', ')}]
  let memberships: i32[][] = [${types.map(t => '[' + t.interfaces.map(i => interfaceNames.indexOf(i.name.value)).join(', ') + ']').join(', ')}]
  let totals = new Array<i32>(interfaceCounters.length)
  let counter = CounterEntity.load('0')
  for (let i = 0; i < types.length; i++) {
    let count = countEntities(types[i])
    if (counter == null) {
      assert.i32Equals(count, 0)
    } else {
      assert.fieldEquals('CounterEntity', '0', typeCounters[i], count.toString())
    }
    for (let j = 0; j < memberships[i].length; j++) totals[memberships[i][j]] += count
  }
  if (counter != null) {
    for (let i = 0; i < interfaceCounters.length; i++) {
      assert.fieldEquals('CounterEntity', '0', interfaceCounters[i], totals[i].toString())
    }
  }
}
`
const generated = {
  'src/mappings/eventCounters.ts': output,
  'tests/counterAssertions.ts': assertionOutput,
}
for (const filename of Object.keys(generated)) {
  const target = path.join(root, filename)
  generated[filename] = prettier.format(generated[filename], {
    ...prettier.resolveConfig.sync(target),
    filepath: target,
  })
}
if (process.argv.includes('--check')) {
  for (const [filename, content] of Object.entries(generated)) {
    const target = path.join(root, filename)
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) throw new Error('Run yarn generate:events to update schema-derived counters')
  }
  // All production activity records must go through the same save/count path.
  for (const filename of fs.readdirSync(path.join(root, 'src/mappings'))) {
    if (!filename.endsWith('.ts')) continue
    const source = fs.readFileSync(path.join(root, 'src/mappings', filename), 'utf8').replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, '')
    for (const match of source.matchAll(/(?:let|const)\s+(\w+)\s*=\s*new\s+(\w+Event)\(/g)) {
      if (new RegExp(`\\b${match[1]}\\.save\\(`).test(source)) throw new Error(`${filename}: direct activity save bypasses counters: ${match[1]}`)
    }
  }
  console.log(`Validated counters for ${types.length} activity types and ${expected.size - types.length} interfaces`)
} else {
  for (const [filename, content] of Object.entries(generated)) fs.writeFileSync(path.join(root, filename), content)
}
